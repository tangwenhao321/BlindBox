-- Admin RBAC tables required before menu seed migrations (fresh Flyway installs).
CREATE TABLE IF NOT EXISTS role (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    created_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    edited_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    creator_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    editor_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    name VARCHAR(36) NOT NULL,
    UNIQUE KEY role_name_uk (name)
);

CREATE TABLE IF NOT EXISTS menu (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    created_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    edited_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    creator_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    editor_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    name VARCHAR(20) NOT NULL,
    path VARCHAR(2000) NOT NULL,
    parent_id VARCHAR(36) NULL,
    order_num INT NULL,
    menu_type VARCHAR(36) NOT NULL,
    icon VARCHAR(255) NULL,
    visible TINYINT(1) NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS role_menu_rel (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    created_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    edited_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    creator_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    editor_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    role_id VARCHAR(36) NOT NULL,
    menu_id VARCHAR(36) NOT NULL
);

CREATE TABLE IF NOT EXISTS user_role_rel (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    created_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    edited_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    creator_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    editor_id VARCHAR(36) NOT NULL DEFAULT '0f07d638f1bc401188d86dc650ab06a7',
    user_id VARCHAR(36) NOT NULL,
    role_id VARCHAR(36) NOT NULL
);

